let total = 0;
let misses = 0;
for (const [file, pairs] of Object.entries(R)) {
  const p = join(DIR, file);
  let raw = readFileSync(p, 'utf8');
  for (const [from, to] of pairs) {
    const count = raw.split(from).length - 1;
    if (count === 0) {
      console.log(`MISS ${file}: ${from.slice(0, 70)}...`);
      misses++;
      continue;
    }
    raw = raw.split(from).join(to);
    total += count;
  }
  writeFileSync(p, raw, 'utf8');
}
console.log(`done: ${total} replacements across ${Object.keys(R).length} files, ${misses} misses`);
