// Normalize visible-text lowercase "olagoon" -> "OLagoon".
// Usage: node scripts/_fix-brand-case.mjs [--apply]
// Excludes: domains (olagoon.com), emails (@), URL slugs (/-prefixed or -followed),
// filenames, storage keys (olagoon_utm), anything preceded by letters.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const APPLY = process.argv.includes('--apply');
const ROOTS = ['src/data', 'src/content', 'src/config.yaml'];

const TARGET =
  /(?<![A-Za-z@/.\-_])olagoon(?![A-Za-z0-9_-])(?!\.com\b)(?![A-Za-z0-9_-]*\.(?:png|jpg|jpeg|webp|gif|svg|ico|xml|json|txt|pdf|html)\b)/g;

let totalMatches = 0;
let totalFiles = 0;
const changedFiles = [];

function processFile(p) {
  const src = readFileSync(p, 'utf8');
  const matches = src.match(TARGET) || [];
  if (matches.length === 0) return;
  totalMatches += matches.length;
  totalFiles++;
  const out = src.replace(TARGET, 'OLagoon');
  if (APPLY) writeFileSync(p, out, 'utf8');
  changedFiles.push({ file: p.replace(/\\/g, '/'), count: matches.length });
}

function walk(p) {
  const st = statSync(p);
  if (st.isDirectory()) {
    for (const name of readdirSync(p)) walk(join(p, name));
  } else if (/\.(yaml|yml|json|jsonc|md|mdx|ts|js|cjs|mjs|astro|txt)$/.test(p)) {
    processFile(p);
  }
}

for (const r of ROOTS) walk(r);

// src pages/components/layouts (i18n/generated is a build artifact — regenerated by build)
for (const d of ['src/pages', 'src/components', 'src/layouts']) {
  walk(d);
}
// workers + functions (user-facing worker strings)
for (const d of ['workers', 'functions']) walk(d);

console.log(`${APPLY ? 'APPLIED' : 'DRY-RUN'}: ${totalMatches} replacements in ${totalFiles} files`);
changedFiles.sort((a, b) => b.count - a.count);
for (const c of changedFiles.slice(0, 40)) console.log(`  ${c.count}\t${c.file}`);
if (changedFiles.length > 40) console.log(`  ... and ${changedFiles.length - 40} more files`);
